#!/usr/bin/env python3
"""Build the student topic list from topics/<slug>.yml.

Reads each `topics/<slug>.yml`, resolves contacts against `members/`, and
writes `docs/_topics.qmd`, which is included by `docs/students.qmd`.

The output is gitignored — CI runs this before `quarto render`.
"""
from __future__ import annotations

from pathlib import Path

import yaml

from build_people import REPO_ROOT, load_members

TOPICS_DIR = REPO_ROOT / "topics"
TOPICS_PARTIAL = REPO_ROOT / "docs" / "_topics.qmd"

LEVEL_ORDER = ("BSc", "MSc")


def load_topics() -> list[dict]:
    topics = []
    for path in sorted(TOPICS_DIR.glob("*.yml")):
        if path.name.startswith((".", "_")):
            continue
        data = yaml.safe_load(path.read_text()) or {}
        for field in ("title", "contact", "description"):
            if field not in data:
                raise ValueError(f"{path.name}: missing required field '{field}'")
        if data.get("status", "open") != "open":
            print(f"  skip {path.name} (status: {data['status']})")
            continue
        data["_slug"] = path.stem
        topics.append(data)
    topics.sort(key=lambda t: t["title"])
    return topics


def as_list(value) -> list:
    if value is None:
        return []
    return value if isinstance(value, list) else [value]


def render_contact(slug: str, members: dict[str, dict]) -> str:
    member = members.get(slug)
    if member is None:
        raise ValueError(f"unknown contact '{slug}' (no members/{slug}/info.yml)")
    email = (member.get("links") or {}).get("email")
    url = f"mailto:{email}" if email else "people/index.qmd"
    return f"[{member['name']}]({url})"


def render_levels(levels: list[str]) -> str:
    for level in levels:
        if level not in LEVEL_ORDER:
            raise ValueError(f"unknown level '{level}' (expected one of {LEVEL_ORDER})")
    ordered = [lvl for lvl in LEVEL_ORDER if lvl in levels]
    return " ".join(f"[{lvl}]{{.topic-level}}" for lvl in ordered)


def render_keywords(keywords: list[str]) -> str:
    return " ".join(f"[{k}]{{.kw}}" for k in keywords)


def render_topic(topic: dict, members: dict[str, dict]) -> str:
    contacts = ", ".join(render_contact(s, members) for s in as_list(topic["contact"]))
    lines = [
        f"::: {{.topic-card #topic-{topic['_slug']}}}",
        f"### {topic['title']} {render_levels(as_list(topic.get('level')))}",
        "",
        topic["description"].strip(),
        "",
        f"[Contact: {contacts}]{{.topic-contact}}",
    ]
    keywords = as_list(topic.get("keywords"))
    if keywords:
        lines += ["", f"[{render_keywords(keywords)}]{{.keywords}}"]
    lines.append(":::")
    return "\n".join(lines)


def main() -> None:
    members = {m["_slug"]: m for m in load_members()}
    topics = load_topics()
    print(f"Found {len(topics)} open topic(s).")

    if topics:
        body = "\n\n".join(render_topic(t, members) for t in topics)
    else:
        body = "_No topics are listed at the moment._"

    TOPICS_PARTIAL.write_text(
        "<!-- AUTO-GENERATED by scripts/build_topics.py — do not edit manually. -->\n\n"
        f"{body}\n"
    )
    print(f"Wrote {TOPICS_PARTIAL.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
